#!/usr/bin/env node
/**
 * Suite 2.0.0 (RFC 0168 §D.3) — `conformance/scenario-majors.json`: which
 * protocol major(s) each scenario file targets. One package, `--target-major`;
 * the runner passes the selected files to vitest. Rule: a file named `v2-*`
 * targets [2]; a file listed in BOTH_MAJORS targets [1, 2] (a v1 scenario that
 * also holds on a v2 host — the dual-stack and coexistence legs); every other
 * file targets [1]. Generated so the manifest cannot drift from the tree.
 *   --write / --check
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const CONF = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(CONF, 'scenario-majors.json');
// A v1 scenario whose obligation holds unchanged at major 2 AND whose gate and
// paths have been made major-aware. Both halves are required: a rule that holds
// is not enough if the file's gate returns early unrecorded (indistinguishable
// from an unadvertised family in the bundle) or its paths are hard-coded `/v1/`
// (a suite 404 reported as a host defect). See the docblock of
// memory-attribution-replay-stable for the pattern.
const BOTH_MAJORS = new Set(['fixtures-valid.test.ts', 'memory-attribution-replay-stable.test.ts']);

/**
 * A third half-requirement, and it fires at the only moment it can be caught.
 *
 * `capabilities.md` line 39: *"`supported` | does not exist; presence of the
 * record is the claim, and a host that does not support a family MUST omit
 * it."* So on a conformant major-2 host that field is absent BY CONSTRUCTION,
 * and a scenario gating on `cap?.supported === true` does not fail there — it
 * reports `inapplicable`, forever, and the family silently stops being tested
 * while looking exactly like a host that does not advertise it.
 *
 * 170 of the 443 major-1-only scenario files gate on a `.supported` seat
 * (`a2a-*`, `agent-*`, the whole `behaviorGate('openwop-…', cap?.supported ===
 * true)` family). Every one is correct TODAY because it only runs at major 1.
 * Promotion is what makes it wrong, so promotion is where the check belongs —
 * it costs two greps and fires exactly when someone is about to create the
 * problem, rather than asking 170 files to be rewritten against a day that may
 * never come.
 *
 * Same shape as the scenario that shipped without a registry row and therefore
 * never ran, arriving through a promotion instead of an omission. Found by the
 * tier-2 host session while checking whether a replay flake could reach its
 * bundles; it could not, and this is what the checking turned up.
 */
const CAPABILITY_SUPPORTED_GATE = /\.supported\s*(?:!==|===|\?|\)|&&|\|\|)|\?\.supported/;
for (const name of [...BOTH_MAJORS].sort()) {
  const file = join(CONF, 'src', 'scenarios', name);
  if (!existsSync(file)) {
    console.error(`generate-scenario-majors: BOTH_MAJORS names ${name}, which does not exist — a promotion list that outlives its file promotes nothing and says nothing`);
    process.exit(1);
  }
  const src = readFileSync(file, 'utf8');
  const offending = src
    .split('\n')
    .map((line, i) => [i + 1, line])
    .filter(([, line]) => CAPABILITY_SUPPORTED_GATE.test(line));
  if (offending.length) {
    console.error(
      `generate-scenario-majors: ${name} is in BOTH_MAJORS but gates on a capability \`.supported\` seat, which capabilities.md line 39 says "does not exist" at major 2 — on every conformant v2 host this records \`inapplicable\` rather than failing, so the family stops being tested and looks like a host that does not advertise it:`,
    );
    for (const [n, line] of offending.slice(0, 5)) console.error(`  ${name}:${n}  ${line.trim().slice(0, 140)}`);
    console.error('  Fix the gate to read presence-of-record (capabilities.md §2) before promoting, or leave the file at [1].');
    process.exit(1);
  }
}
const files = readdirSync(join(CONF, 'src', 'scenarios')).filter((f) => f.endsWith('.test.ts')).sort();
const majors = Object.fromEntries(files.map((f) => [f, f.startsWith('v2-') ? [2] : BOTH_MAJORS.has(f) ? [1, 2] : [1]]));
const doc = { $comment: 'GENERATED by conformance/scripts/generate-scenario-majors.mjs (RFC 0168 §D.3). Do not edit; add a file to BOTH_MAJORS in the generator to target both majors.', counts: { files: files.length, v1: files.filter((f) => majors[f].includes(1)).length, v2: files.filter((f) => majors[f].includes(2)).length }, majors };
const render = JSON.stringify(doc, null, 2) + '\n';
if (process.argv.includes('--write')) { writeFileSync(OUT, render); console.log(`wrote scenario-majors.json: ${doc.counts.files} files (v1 ${doc.counts.v1}, v2 ${doc.counts.v2})`); }
else if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== render) { console.error('scenario-majors.json is stale — run: node conformance/scripts/generate-scenario-majors.mjs --write'); process.exit(1); }
else console.log(`=== scenario-majors OK — ${doc.counts.files} files (v1 ${doc.counts.v1}, v2 ${doc.counts.v2}) ===`);
