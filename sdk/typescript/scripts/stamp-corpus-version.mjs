#!/usr/bin/env node
/**
 * Stamp src/corpusVersion.ts with the corpus release this SDK build corresponds
 * to — the nearest corpus `v*` git tag reachable from HEAD, plus the commit SHA.
 *
 * Runs automatically on `npm publish` via the package's `prepublishOnly` hook
 * (so every publish path — corpus-aligned `v*`, SDK-only `openwop/v*`, or a local
 * publish — gets stamped). Per-package tags start with a prefix (`openwop/`,
 * `sdk/go/`, …) so `--match 'v*'` deliberately skips them and resolves the
 * corpus tag the build actually sits on.
 *
 * Falls back to the committed dev sentinel when git or tags are unavailable
 * (plain `tsc`, fork builds, shallow checkout without tags) so the build never
 * breaks — CI publish must use `actions/checkout` with `fetch-depth: 0`.
 */
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'src', 'corpusVersion.ts');

function git(args) {
  try {
    return execSync(`git ${args}`, { cwd: here, stdio: ['ignore', 'pipe', 'ignore'] })
      .toString()
      .trim();
  } catch {
    return '';
  }
}

const tag = git("describe --tags --match 'v*' --abbrev=0 HEAD") || '0.0.0-dev';
const commit = git('rev-parse --short HEAD') || 'unknown';

const body = `// AUTO-GENERATED by scripts/stamp-corpus-version.mjs at publish time.
// DO NOT EDIT — the committed values are a dev sentinel; the PUBLISHED package
// carries the real corpus tag (stamped via \`prepublishOnly\`). See the
// openwop-app extraction plan §"version-coherence gate": this is the anchor an
// extracted app uses to assert its vendored spec artifacts (schemas / fixtures /
// packs) match the corpus release this SDK was built from.

/** The nearest corpus \`v*\` release this SDK build corresponds to, e.g. "v1.1.7".
 *  \`"0.0.0-dev"\` in a working tree / unstamped build. */
export const CORPUS_VERSION = ${JSON.stringify(tag)} as const;

/** The exact monorepo commit this SDK build was produced from (short SHA). */
export const CORPUS_COMMIT = ${JSON.stringify(commit)} as const;
`;

writeFileSync(target, body);
console.log(`stamped corpusVersion.ts → CORPUS_VERSION=${tag} CORPUS_COMMIT=${commit}`);
