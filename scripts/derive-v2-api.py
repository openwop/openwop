#!/usr/bin/env python3
"""Derive spec/v2/core/headers.md and spec/v2/path-manifest.json from the v2 API
documents (RFC 0172 §C.2, RFC 0171 §C.1, RFC 0168 §C.2).

`api/v2/openapi.yaml`, `api/v2/asyncapi.yaml` and `api/seams-v2.yaml` are their
own source and are edited by hand (RFC 0266 §C.1). Until 2.49.12 this script
also built them from the frozen v1 documents (`api/openapi.yaml`,
`api/asyncapi.yaml`) through a prose overlay; the cut-over (RFC 0266 §C) checked
that the committed v2 files equalled that derivation byte for byte, and the v1
inputs were dropped. This script reads no v1 file.

What it derives, from the v2 API documents and spec/v2/release.json only:
  - `info.version` of api/v2/openapi.yaml, api/v2/asyncapi.yaml and
    api/seams-v2.yaml reads spec/v2/release.json (RFC 0172 §B axis 14); --write
    rewrites that one line in place and leaves the rest of each file as edited;
  - spec/v2/core/headers.md: every request and response header the OpenAPI
    document declares, with the operation count and meaning (RFC 0171 §C.1);
  - spec/v2/path-manifest.json: the canonical v2 operations and channels, with
    the per-operation facts headers.md §Cross-origin preflight derives the
    admitted set from (RFC 0172 §C.2, openwop#1763).

Python + PyYAML because the corpus has no Node YAML parser; the outputs are
committed and `--check` compares a regeneration to the committed bytes, so a CI
without PyYAML fails loudly, never silently.

  --write   regenerate the outputs        --check  compare to the committed files
"""
import json, re, sys
from pathlib import Path
try:
    import yaml
except ModuleNotFoundError:
    sys.exit('derive-v2-api: PyYAML is required (python3 -m pip install pyyaml) — the check refuses to pass without it')

ROOT = Path(__file__).resolve().parent.parent
REL = json.loads((ROOT / 'spec' / 'v2' / 'release.json').read_text())
API_DOCS = [ROOT / 'api' / 'v2' / 'openapi.yaml', ROOT / 'api' / 'v2' / 'asyncapi.yaml', ROOT / 'api' / 'seams-v2.yaml']

def with_release_version(text):
    """The document with its `info.version` line set to spec/v2/release.json's version."""
    m = re.search(r'^info:\n(?:  .*\n)*?  version: (.*)\n', text, re.M)
    if m is None:
        raise SystemExit('derive-v2-api: no `info.version` line found')
    return text[:m.start(1)] + REL['version'] + text[m.end(1):]

API_TEXT = {p: p.read_text() for p in API_DOCS}
doc = yaml.safe_load(with_release_version(API_TEXT[API_DOCS[0]]))
adoc = yaml.safe_load(with_release_version(API_TEXT[API_DOCS[1]]))

def manifest(doc, adoc):
    ops = []
    params = doc.get('components', {}).get('parameters', {})
    for key, item in doc['paths'].items():
        for method, op in item.items():
            if method in ('get', 'post', 'put', 'delete', 'patch'):
                # openwop#1763: the facts headers.md §Cross-origin preflight derives an operation's admitted
                # set from, so the suite reads them here rather than parsing openapi.yaml.
                declared = [params.get(p['$ref'].split('/')[-1], {}) if '$ref' in p else p for p in op.get('parameters', []) + item.get('parameters', [])]
                security = op.get('security', doc.get('security', []))
                ops.append({'method': method.upper(), 'path': key, 'operationId': op.get('operationId'),
                            'requestHeaders': sorted({d['name'] for d in declared if d.get('in') == 'header'}),
                            'authenticated': any(len(r) > 0 for r in security),
                            'requestBody': 'requestBody' in op})
    ops.sort(key=lambda o: (o['path'], o['method']))
    chans = [{'name': n, 'address': c['address']} for n, c in adoc['channels'].items()]
    return {'$comment': 'GENERATED by scripts/derive-v2-api.py (RFC 0172 §C.2 / RFC 0168 §C.2): the canonical v2 operations and channels; no seam or test-mode operation; every path unversioned. check-path-parity.mjs compares this to both API documents. Per operation, requestHeaders / authenticated / requestBody are the facts headers.md §Cross-origin preflight derives the admitted set from.', 'generatedFrom': ['api/v2/openapi.yaml', 'api/v2/asyncapi.yaml'], 'serverUrl': 'https://{host}', 'operations': ops, 'channels': chans, 'counts': {'operations': len(ops), 'channels': len(chans)}}

def first_para(text):
    """The first paragraph of an OpenAPI description, joined onto one line (a
    description wrapped across lines was cut mid-sentence by a first-line split)."""
    return ' '.join(text.strip().split('\n\n')[0].split())

def cell(text):
    """A headers.md table cell: drop a leading openwop RFC citation ("RFC 0172 §A.3 —",
    "RFC 0165 §C.2;", "RFC 0115.") — the doc's Sources line carries provenance."""
    text = re.sub(r'^RFC 0\d{3}(?: §[A-Z0-9][\w.–-]*)?\s*(?:—|;|\.)\s*', '', text)
    text = re.sub(r'\s*Closes F\d+\.$', '', text)  # internal gap-tracker tag
    text = re.sub(r'^[a-z-]+\.md §\w+\.\s*', '', text)  # a bare cross-ref lead-in; the cell restates it
    return text[:1].upper() + text[1:]

def headers_doc(doc):
    """spec/v2/core/headers.md — GENERATED (RFC 0171 §C.1): every non-standard
    header is declared in OpenAPI, so the table that enumerates headers enumerates
    all of them."""
    req, resp = {}, {}
    comps = doc.get('components', {})
    def param_of(p):
        if '$ref' in p:
            return comps.get('parameters', {}).get(p['$ref'].split('/')[-1], {})
        return p
    for key, item in doc['paths'].items():
        for method, op in item.items():
            if method not in ('get', 'post', 'put', 'delete', 'patch'):
                continue
            for p in op.get('parameters', []) + item.get('parameters', []):
                pp = param_of(p)
                if pp.get('in') == 'header':
                    req.setdefault(pp['name'], {'desc': first_para(pp.get('description', '')), 'ops': set()})['ops'].add(op.get('operationId'))
            for code, r in op.get('responses', {}).items():
                rr = comps.get('responses', {}).get(r['$ref'].split('/')[-1], {}) if '$ref' in r else r
                for hn, h in (rr.get('headers') or {}).items():
                    hh = comps.get('headers', {}).get(h['$ref'].split('/')[-1], {}) if '$ref' in h else h
                    resp.setdefault(hn, {'desc': first_para(hh.get('description') or ''), 'ops': set()})['ops'].add(op.get('operationId'))
    lines = ['# Headers', '', '> **Status: Stable.** Generated from `api/v2/openapi.yaml` by `scripts/derive-v2-api.py`; do not edit.', '',
             '## Why this exists', '', 'Every non-standard header is named `OpenWOP-<Name>`, and every header is declared in OpenAPI. These tables are generated from that declaration, so they list all of them: a header not listed here is not part of the protocol.', '',
             'Standard headers keep their standard names: `Idempotency-Key`, `ETag`, `If-None-Match`, `Last-Event-ID`, `Retry-After`, `Authorization`.', '',
             '## Request headers', '', '| Header | Operations | Meaning |', '| --- | --- | --- |']
    for n in sorted(req):
        lines.append(f"| `{n}` | {len(req[n]['ops'])} | {cell(req[n]['desc'])} |")
    # openwop#1763 (Class 3): a browser client sends OpenWOP-Version and OpenWOP-Client-Version on
    # every request (versioning.md §1.3, §1.5), so a host that grants an origin but refuses them in
    # preflight makes a conforming browser client impossible. The admitted set is the one above.
    lines += ['', '## Cross-origin preflight', '',
              'A host granting an origin (`Access-Control-Allow-Origin`) in a CORS preflight for an operation MUST admit the operation\'s method in `Access-Control-Allow-Methods` and, in `Access-Control-Allow-Headers`, every request header `api/v2/openapi.yaml` declares for it, `Authorization` when it is authenticated and `Content-Type` when it takes a body, by listing them or by reflecting `Access-Control-Request-Headers`. A `*` does not admit `Authorization`. Which origins to grant, and whether with credentials, is host policy. Admitting this table\'s union on every operation conforms.']
    lines += ['', '## Response headers', '', '| Header | Operations | Meaning |', '| --- | --- | --- |']
    # A standard header shared by operations with different obligations gets one neutral
    # row; the MUST/SHOULD lives on each operation (D2, 2.36.2).
    shared = {'Cache-Control': 'Standard HTTP caching directive (RFC 9111), set per operation: public content-page delivery, and prompt templates (immutable semantics when the version was pinned); see each operation.',
              'ETag': 'Standard HTTP validator (RFC 9110 §8.8.3). The obligation is per operation: MUST on the discovery document (capabilities.md §1), SHOULD on the run snapshot (runs.md §Snapshot), a content hash on a prompt template (getPromptTemplate); see each operation.'}
    for n in sorted(resp):
        lines.append(f"| `{n}` | {len(resp[n]['ops'])} | {cell(shared.get(n, resp[n]['desc']))} |")
    lines += ['', '## Webhook delivery headers', '', 'Declared in `webhooks.md`, not in OpenAPI, because the host is the client:', '',
              '- `OpenWOP-Webhook-Id`, `OpenWOP-Event-Type`, `OpenWOP-Timestamp`, `OpenWOP-Signature`, `OpenWOP-Signature-Algorithm`.',
              "- On a subscription that opted into Standard Webhooks (webhooks.md): that standard's `webhook-id`, `webhook-timestamp` and `webhook-signature`, under their standard names.",
              '- During the v1 overlap only: the `X-openwop-*` family, emitted beside them and removed at v1 end-of-support.', '',
              '## Removed in v2', '', 'These header names are not part of v2: `Capabilities-Etag` (use the standard `ETag`/`If-None-Match` pair), `X-Dedup`, `X-Force-Engine-Version`, `X-Pack-Sha256`, `X-Pack-Signing-Method`, `X-openwop-*` (webhooks), `openwop-Webhook-Signature`.', '',
              '*Sources: RFC 0165, RFC 0171, RFC 0172, RFC 0201.*', '']
    return '\n'.join(lines)


man = manifest(doc, adoc)
outputs = {ROOT / 'spec' / 'v2' / 'core' / 'headers.md': headers_doc(doc), ROOT / 'spec' / 'v2' / 'path-manifest.json': json.dumps(man, indent=2, ensure_ascii=False) + '\n'}
outputs.update({p: with_release_version(s) for p, s in API_TEXT.items()})
if '--write' in sys.argv:
    for p, s in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True); p.write_text(s); print(f'wrote {p.relative_to(ROOT)}')
    print(f"derive-v2-api: {man['counts']['operations']} operations, {man['counts']['channels']} channels")
else:
    stale = [str(p.relative_to(ROOT)) for p, s in outputs.items() if not p.exists() or p.read_text() != s]
    if stale:
        print('derive-v2-api: stale — ' + ', '.join(stale) + '. Run: python3 scripts/derive-v2-api.py --write', file=sys.stderr); sys.exit(1)
    print(f"=== derive-v2-api OK — {man['counts']['operations']} operations / {man['counts']['channels']} channels; headers.md and path-manifest.json in parity with api/v2; info.version {REL['version']} ===")
