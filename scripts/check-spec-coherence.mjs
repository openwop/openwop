#!/usr/bin/env node
/**
 * RFC 0168 §D.1 / RFC 0174 §B.1 — run the corpus-coherence scenarios
 * (conformance/src/coherence/) in the spec repo's CI and emit the corpus ledger
 * `evidence/corpus-ledger.json`: one entry per requirement id with its result,
 * the evidence check-accepted-predicate.mjs accepts for `(corpus)` falsifiability
 * rows ("corpus gate — no host tier", GOVERNANCE §"Acceptance evidence tiers").
 *
 * These scenarios read spec/, schemas/, api/ and assert nothing about a host;
 * they never enter a host bundle and are never packed. They run under
 * conformance/vitest.coherence.config.ts with the per-`it` ledger enabled so
 * every `it` records its requirement id (req(), RFC 0168 §A.1).
 *
 *   --write   run and rewrite evidence/corpus-ledger.json
 *   --check   run and fail if the ledger on disk disagrees with the run
 *             (ids and results; timestamps are not compared)
 */
import { spawn } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CONF = join(ROOT, 'conformance');
const OUT = join(ROOT, 'evidence', 'corpus-ledger.json');
const write = process.argv.includes('--write');

const ledgerDir = mkdtempSync(join(tmpdir(), 'owp-corpus-ledger-'));
const ledgerPath = join(ledgerDir, 'ledger.jsonl');
// "No host" made concrete: a stub that serves a minimal discovery document
// advertising nothing and 404s everything else, so a coherence scenario's
// capability-gated host leg records `inapplicable` (not advertised) instead of
// failing on an unreachable address. It asserts nothing about any host.
import { createServer } from 'node:http';
const stub = createServer((req, res) => {
  if (req.url === '/.well-known/openwop') { res.writeHead(200, { 'content-type': 'application/json' }); res.end(JSON.stringify({ protocolVersion: '1.1', protocolVersions: ['1.1'], supportedEnvelopes: [], schemaVersions: {}, limits: {}, fixtures: { supported: false, advertised: [] } })); return; }
  res.writeHead(404, { 'content-type': 'application/json' }); res.end(JSON.stringify({ error: 'not_found', message: 'corpus-gate stub: no host' }));
});
await new Promise((r) => stub.listen(0, '127.0.0.1', r));
const stubUrl = `http://127.0.0.1:${stub.address().port}`;
const env = { ...process.env, OPENWOP_LEDGER_PATH: ledgerPath, OPENWOP_CONFORMANCE_ROOT: ROOT, OPENWOP_BASE_URL: stubUrl, OPENWOP_API_KEY: 'corpus-gate', OPENWOP_DISPOSITION_SUMMARY: 'false', OPENWOP_CORPUS_GATE: '1' };
// Async spawn: the stub above lives in THIS process, so a blocking spawnSync
// would starve it and every host leg would time out (measured 2026-09-03).
const run = await new Promise((resolve) => {
  const child = spawn('npx', ['vitest', 'run', '--config', 'vitest.coherence.config.ts'], { cwd: CONF, env, stdio: ['ignore', 'pipe', 'pipe'] });
  let stdout = '', stderr = '';
  child.stdout.on('data', (d) => { stdout += d; }); child.stderr.on('data', (d) => { stderr += d; });
  child.on('close', (status) => resolve({ status, stdout, stderr }));
});
stub.close();
const tail = (run.stdout + run.stderr).split('\n').filter((l) => /Test Files|Tests |FAIL|✓|×/.test(l)).slice(-6).join('\n');
if (run.status !== 0) { console.error(`=== check-spec-coherence FAILED — a corpus-coherence scenario failed ===\n${(run.stdout + run.stderr).split('\n').filter((l) => /FAIL|×|Error|expected/.test(l)).slice(0, 40).join('\n')}`); process.exit(1); }

const rows = existsSync(ledgerPath) ? readFileSync(ledgerPath, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)) : [];
const requirements = {};
for (const r of rows) {
  const id = r.requirementId ?? r.id; if (!id) continue;
  (requirements[id] ??= []).push({ result: r.disposition, scenario: r.scenario ?? r.file ?? null });
}
const ledger = { $comment: 'GENERATED by scripts/check-spec-coherence.mjs — the corpus ledger (RFC 0168 §D.1): per-requirement results of the corpus-coherence scenarios, run in the spec repo CI, never in a host bundle. check-accepted-predicate.mjs reads it for (corpus) falsifiability rows.', generated: new Date().toISOString().slice(0, 10), suiteVersion: JSON.parse(readFileSync(join(CONF, 'package.json'), 'utf8')).version, scenarios: rows.length, requirements };
// Compared: the ID SET only. Results legitimately differ by environment — a
// coherence leg that reads a sibling checkout (openwop-sdks parity) is
// executed-pass where the sibling is present and blocked where it is not —
// so the committed ledger (written with the siblings present) is the fuller
// evidence and CI checks that the set of ids it names is the set the tree
// produces. Result drift is REPORTED, never silently accepted.
// The tree's id set must be a SUBSET of the committed ledger's: a coherence
// scenario that generates one `it` per sibling-repo file produces no rows in a
// CI that has no siblings, so equality would fail there for no defect; a NEW
// test in the tree that the committed ledger does not name still fails.
const idsOf = (o) => Object.keys(o.requirements).sort();
const strip = (o) => JSON.stringify({ suiteVersion: o.suiteVersion, ids: idsOf(o) });
const resultDrift = (a, b) => Object.keys(a.requirements).filter((k) => b.requirements[k] && JSON.stringify(a.requirements[k].map((r) => r.result).sort()) !== JSON.stringify(b.requirements[k].map((r) => r.result).sort()));
if (write) { writeFileSync(OUT, JSON.stringify(ledger, null, 2) + '\n'); console.log(`wrote evidence/corpus-ledger.json: ${Object.keys(requirements).length} requirement id(s) from ${rows.length} ledger row(s)\n${tail}`); }
else {
  const prev = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')) : null;
  const committed = prev ? new Set(idsOf(prev)) : new Set();
  const missing = idsOf(ledger).filter((id) => !committed.has(id));
  if (!prev || prev.suiteVersion !== ledger.suiteVersion || missing.length) { console.error(`=== check-spec-coherence FAILED — evidence/corpus-ledger.json ${!prev ? 'is missing' : prev.suiteVersion !== ledger.suiteVersion ? `is for suite ${prev.suiteVersion}, tree is ${ledger.suiteVersion}` : `does not name ${missing.length} id(s) the tree produces: ${missing.slice(0, 5).join(', ')}`}; run: node scripts/check-spec-coherence.mjs --write ===`); process.exit(1); }
  const committedOnly = idsOf(prev).filter((id) => !(id in ledger.requirements));
  if (committedOnly.length) console.log(`  note: ${committedOnly.length} committed id(s) did not run in this environment (sibling-checkout legs)`);
  const drift = resultDrift(prev, ledger);
  if (drift.length) console.log(`  note: ${drift.length} id(s) record a different result in this environment than the committed ledger (sibling-checkout legs); the committed ledger is the evidence: ${drift.slice(0, 5).join(', ')}${drift.length > 5 ? ', …' : ''}`);
  const pass = Object.values(prev.requirements).flat().filter((r) => r.result === 'executed-pass').length;
  console.log(`=== check-spec-coherence OK — ${Object.keys(requirements).length} requirement id(s) in the corpus ledger (${pass} executed-pass rows committed); ${rows.length} ledger row(s) ===\n${tail}`);
}
