#!/usr/bin/env node
/**
 * generate-event-codemap — `spec/v1/event-codemap.json`, the v1→v2 event-type
 * codemap AS DATA (v2 charter C.4 / C.9; Phase 1 item 9).
 *
 * One row per `RunEventType` enum member: the v1 name, the payload `$def` it is
 * keyed to today, and a PROPOSED v2 name under the charter's one naming rule
 * (`domain.verb-ed`, kebab inside segments, two segments, no reserved `core.`
 * prefix). Nothing consumes this file yet — that is the point. When the v2 C.4
 * child RFC renames the vocabulary it edits THIS file, not prose, and every
 * host backfills its event log from the same map (Axiom 6: nothing persisted
 * under v1 is orphaned).
 *
 * The proposed names are mechanical (case and separator normalisation only).
 * Semantic renames — tense (`voice.speech_start` → `speech-started`?),
 * domain merges (`runOrchestrator` ↔ `run`), splitting `core.*` — are C.4
 * decisions and are flagged `review: true` here rather than guessed.
 *
 *   --write   regenerate; hand fields (v2 override, note) survive
 *   --check   fail when stale, when a row's v1 type left the enum, when two
 *             rows propose the same v2 name, or when a v2 name breaks grammar
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'spec', 'v1', 'event-codemap.json');
const V2_GRAMMAR = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*\.[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

const kebab = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/_/g, '-')
    .toLowerCase();

/** Mechanical v2 proposal: drop reserved `core.`, kebab every segment, fold 3+ segments into domain.rest-joined. */
function propose(v1) {
  let segs = v1.split('.');
  let review = false;
  const notes = [];
  if (segs[0] === 'core') {
    segs = segs.slice(1);
    notes.push('reserved `core.` prefix dropped (the vendor regex reserves it)');
    review = true;
  }
  const domain = kebab(segs[0]);
  const rest = segs.slice(1).map(kebab);
  if (rest.length === 0) {
    review = true;
    notes.push('single segment — needs a verb');
  }
  if (rest.length > 1) notes.push(`${rest.length + 1} segments folded to two`);
  const verb = rest.join('-');
  if (/[A-Z_]/.test(v1)) notes.push('case/separator normalised');
  if (!/(ed|en|t|d)$/.test(verb.split('-').pop() ?? '')) {
    review = true;
    notes.push('verb is not past-tense — tense is a C.4 decision, not normalised here');
  }
  if (domain !== segs[0]) {
    review = true;
    notes.push(`domain \`${segs[0]}\` renamed \`${domain}\` — confirm it is the same domain as \`${domain.split('-')[0]}\``);
  }
  return { v2: `${domain}.${verb}`, review, notes };
}

export function generate(prev) {
  const ev = JSON.parse(readFileSync(join(ROOT, 'schemas', 'run-event.schema.json'), 'utf8'));
  const payloads = JSON.parse(readFileSync(join(ROOT, 'schemas', 'run-event-payloads.schema.json'), 'utf8'));
  const index = payloads.$defs._typeIndex.properties;
  const prevByV1 = new Map((prev.rows ?? []).map((r) => [r.v1, r]));
  const rows = [];
  for (const v1 of ev.$defs.RunEventType.enum) {
    const old = prevByV1.get(v1);
    const p = propose(v1);
    const ref = index[v1]?.$ref ?? null;
    rows.push({
      v1,
      v2: old?.v2Override ?? p.v2,
      ...(old?.v2Override ? { v2Override: old.v2Override } : {}),
      payloadDef: ref ? ref.replace('#/$defs/', '') : null,
      status: old?.status ?? 'proposed',
      review: old?.v2Override ? false : p.review,
      notes: p.notes,
      ...(old?.note ? { note: old.note } : {}),
    });
  }
  return {
    $schema: './event-codemap.schema.json',
    $comment:
      'GENERATED by scripts/generate-event-codemap.mjs from schemas/run-event.schema.json + run-event-payloads.schema.json. v2 names are MECHANICAL PROPOSALS (v2 charter C.4 naming rule: domain.verb-ed, kebab, two segments, no reserved core. prefix); `review: true` marks rows needing a semantic decision. Hand fields v2Override / note / status survive regeneration. No consumer reads this in v1.x; the v2 C.4 child RFC edits it and every host backfills from it.',
    version: 1,
    updated: prev.updated ?? '2026-09-02',
    grammar: V2_GRAMMAR.source,
    counts: { rows: rows.length, review: rows.filter((r) => r.review).length, overridden: rows.filter((r) => r.v2Override).length },
    rows,
  };
}

const stable = (o) => JSON.stringify(o, null, 2) + '\n';
const mode = process.argv.includes('--write') ? 'write' : process.argv.includes('--check') ? 'check' : 'report';
const prev = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')) : {};
const fresh = generate(prev);

const problems = [];
const seen = new Map();
for (const r of fresh.rows) {
  if (!V2_GRAMMAR.test(r.v2)) problems.push(`${r.v1}: proposed v2 name ${r.v2} breaks the grammar`);
  if (seen.has(r.v2)) problems.push(`${r.v1} and ${seen.get(r.v2)} both map to ${r.v2}`);
  seen.set(r.v2, r.v1);
  if (r.payloadDef === null) problems.push(`${r.v1}: no payload $def in run-event-payloads.schema.json _typeIndex`);
}

if (mode === 'write') {
  fresh.updated = new Date().toISOString().slice(0, 10);
  writeFileSync(OUT, stable(fresh));
  console.log(`wrote spec/v1/event-codemap.json: ${fresh.counts.rows} rows (${fresh.counts.review} need a C.4 decision, ${fresh.counts.overridden} overridden)${problems.length ? `; ${problems.length} problem(s): ${problems.slice(0, 5).join('; ')}` : ''}`);
} else if (mode === 'check') {
  if (!existsSync(OUT)) problems.push('spec/v1/event-codemap.json is missing — run generate-event-codemap.mjs --write');
  else if (stable({ ...prev, updated: 'x' }) !== stable({ ...fresh, updated: 'x' })) problems.push('spec/v1/event-codemap.json is stale against the event enum — run generate-event-codemap.mjs --write');
  if (problems.length > 0) {
    console.error(`=== check-event-codemap FAILED — ${problems.length} problem(s) ===`);
    for (const p of problems.slice(0, 30)) console.error(`  ${p}`);
    process.exit(1);
  }
  console.log(`=== check-event-codemap OK — ${fresh.counts.rows} event types mapped, ${fresh.counts.review} awaiting a C.4 decision, v2 names unique and grammatical ===`);
} else {
  console.log(JSON.stringify({ ...fresh.counts, problems }, null, 2));
}
